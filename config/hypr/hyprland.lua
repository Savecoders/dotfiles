-- Main Hyprland Lua Configuration Entrypoint
-- https://wiki.hypr.land/

hl.config({ autogenerated = false })

-- loadfile avoids Hyprland's require watcher for Matugen's generated palette.
local colors = {}
local directory = debug.getinfo(1, "S").source:sub(2):match("^(.*[/])")
local palettePath = assert(directory, "Hyprland configuration needs a file path") .. "config/colors.lua"
local initialKeys

local function readPalette()
    local chunk = loadfile(palettePath, "t", {})
    if not chunk then return nil end
    local ok, palette = pcall(chunk)
    if not ok or type(palette) ~= "table" then return nil end
    for key, value in pairs(palette) do
        if type(key) ~= "string" or type(value) ~= "string" then return nil end
        if not value:match("^#%x%x%x%x%x%x$") and not value:match("^rgba%(%x%x%x%x%x%x%x%x%)$") then
            return nil
        end
    end
    if not palette.on_primary or not palette.on_secondary then return nil end
    if initialKeys then
        for key in pairs(initialKeys) do
            if not palette[key] then return nil end
        end
    end
    return palette
end

local function publish(palette)
    for key in pairs(colors) do colors[key] = nil end
    for key, value in pairs(palette) do colors[key] = value end
end

local function activeBorder(palette)
    palette = palette or colors
    return { colors = { palette.on_primary, palette.on_secondary }, angle = 45 }
end

local function refreshColors()
    local palette = readPalette()
    if not palette then return "THEME1:error" end
    local ok = pcall(hl.config, { general = { col = { active_border = activeBorder(palette) } } })
    if not ok then return "THEME1:error" end
    publish(palette)
    return "THEME1:ok"
end

local initial = assert(readPalette(), "Invalid Hyprland theme palette")
initialKeys = initial
publish(initial)
-- Keep cached palette references stable; reload-dependent callbacks do not run.
package.loaded["config.colors"] = colors
_savior_hypr_colors = { colors = colors, activeBorder = activeBorder, refresh = refreshColors }
-- Older Matugen hooks and custom imports can use the cached API without loading a file.
package.loaded["config.theme"] = _savior_hypr_colors

require("config.apps")
require("config.autostart")
require("config.environment")
require("config.rules")
require("config.general")
require("config.keybinds")
require("nvidia")

-- Load custom configurations with pcall to ensure it doesn't crash if they are absent or empty
pcall(require, "custom.colors")
pcall(require, "custom.apps")
pcall(require, "custom.autostart")
pcall(require, "custom.general")
pcall(require, "custom.keybinds")
pcall(require, "custom.environment")
pcall(require, "custom.rules")
